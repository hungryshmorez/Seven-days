// Second pass: cinematic prologue (roam) -> Day 1 (roam) -> VCR room -> search Day 1 as a tape
const { open } = require('./lib.cjs');
(async () => {
  const [dist, out] = process.argv.slice(2);
  const t = await open(dist, out);
  const { page, shot, state } = t;
  await page.waitForSelector('text=NEW GAME', { timeout: 30000 });
  await page.click('text=NEW GAME');
  await page.waitForTimeout(800);
  await page.evaluate(() => { window.__journey.searchLoop({ cp: { id: 'x', x: 0, z: 0, yaw: 0, mode: 'out', chase: false }, flash: true, clues: [], bolted: false, loopPass: 0, friendsAlive: [], tapesFound: [], tapesWatched: [], pendingTape: null }); });
  await page.waitForTimeout(1500);
  console.log('seg', JSON.stringify(await state()));
  await page.waitForTimeout(2500);
  await shot('10_prologue_roam_start');
  await page.evaluate(() => { window.__sd_cine.dir.time = 86; });
  await page.waitForTimeout(2500);
  await shot('10b_beach_start');
  await page.keyboard.down('w'); await page.waitForTimeout(3500);
  const pos = await page.evaluate(() => { const e = window.__sd_cine; return { x: e.rig.pos.x, z: e.rig.pos.z, time: e.dir.time, fr: e.opts.freeRoam }; });
  console.log('prologue pos after walking', JSON.stringify(pos));
  await page.keyboard.up('w');
  await shot('11_prologue_roam_walked');
  const waitFor = async (fn, ms = 90000, label = '') => { const t0 = Date.now(); while (Date.now() - t0 < ms) { try { if (await page.evaluate(fn)) return true; } catch (e) {} await page.waitForTimeout(500); } console.log('TIMEOUT waiting for', label); return false; };
  await page.evaluate(() => { const e = window.__sd_cine; e.dir.time = 105; });
  await waitFor(() => window.__sd_cine.dir.time >= 104.9, 20000, 'hold');
  await page.waitForTimeout(1500);
  console.log('held at', await page.evaluate(() => window.__sd_cine.dir.time));
  await page.evaluate(() => { const e = window.__sd_cine; e.fr.off.set(-3.4 - e.fr.rail.x + 1, 0, -7.4 - e.fr.rail.z + 1); });
  await waitFor(() => window.__sd_cine.holdDone, 20000, 'camp');
  await page.evaluate(() => { window.__sd_cine.dir.time = 141; });
  await waitFor(() => window.__journey.get().state.seg.ep === 'day1', 90000, 'day1');
  console.log('seg', JSON.stringify(await state()));
  await waitFor(() => window.__sd_cine && window.__sd_cine.opts.freeRoam && window.__sd_cine.dir.time > 3, 60000, 'day1 running');
  await shot('12_day1_roam');
  await page.evaluate(() => { window.__sd_cine.finish(); });
  await waitFor(() => window.__sd_cine && window.__sd_cine.vcrActive, 120000, 'vcr');
  await page.waitForTimeout(3000);
  await shot('13_vcr_room');
  await page.evaluate(() => { const e = window.__sd_cine; e.rig.pos.set(-0.9, 1.55, 1.6); });
  await page.waitForTimeout(800);
  await page.keyboard.press('e'); await page.waitForTimeout(1500);
  await shot('14_vcr_tape_taken');
  await page.evaluate(() => { const e = window.__sd_cine; e.rig.pos.set(0.9, 1.55, -1.2); });
  await page.waitForTimeout(800);
  await page.keyboard.press('e');
  await waitFor(() => window.__journey.get().state.seg.k === 'tapeday', 120000, 'tapeday seg');
  console.log('after vcr', JSON.stringify(await state()));
  await waitFor(() => !!(window.__sd_search && window.__sd_search.tapeMode), 60000, 'tape mode');
  await page.waitForTimeout(2500);
  await shot('16_tapeday1');
  for (let i = 0; i < 6; i++) { await page.evaluate(() => { window.__sd_search.clock += 4; }); await page.waitForTimeout(2500); }
  await shot('17_tapeday1_later');
  console.log('route', await page.evaluate(() => { const g = window.__sd_search; return { n: g.tapeRoute.length, used: g.tapeUsed.size, p: [g.p.x, g.p.z], clock: g.tapeClock, mode: g.mode, state: g.state }; }));
  console.log('errors', t.errs.length);
  await t.close();
})();
